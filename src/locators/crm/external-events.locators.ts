import { type Locator, type Page } from '@playwright/test';

/** External Events list, under the CRM module (confirmed against the running app). */
export const EXTERNAL_EVENTS_LIST_PATH = '/crm/events';

/** Escapes a literal string for use inside a RegExp (event titles can contain "|", "." etc.). */
const escapeRegExp = (text: string): string => text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Raw element locators for "Create External Event" (CRM, Sprint 4 user
 * story) — no actions or assertions here, see
 * src/pages/crm/external-events.page.ts for those.
 *
 * Confirmed against the running app (2026-09-25):
 * - The list screen's entry point is a "Create Event" button (not
 *   "Create External Event") that navigates to its own route
 *   (`/crm/events/new`).
 * - "External Event Date" is a native `<input type="date">` — fill with
 *   an ISO string (e.g. "2026-09-20"), same idiom as every other native
 *   date field already confirmed elsewhere in this app.
 * - "SAITEX Attendees" is a button that opens a popup dialog with a
 *   `listbox` of employee names, not a combobox — selecting one closes
 *   the popup automatically (unlike the Notify Internally multi-select
 *   elsewhere in this app, which needs an explicit dismiss — see
 *   log-communication.page.ts's selectNotifyManager() for that
 *   contrast).
 * - The ClickUp text names only SAITEX Attendees/Score/Number of Leads as
 *   mandatory Feedback Form fields. Confirmed directly this is
 *   incomplete: "What went well?", "What could have been better?", and
 *   "Attend next editions?" are ALSO required — Submit is blocked with
 *   field-level "Required" errors on all three otherwise.
 * - Submit does not save immediately — it opens a confirmation dialog
 *   ("External Event created!", warning that all Managers get notified)
 *   with "Keep editing"/"Save event"; only "Save event" persists it and
 *   redirects to the new event's own Details screen
 *   (`/crm/events/{id}?tab=feedback`).
 *
 * Also covers the List screen (CRM Sprint 3 — "External Events List
 * screen") and the event's own Details/workspace (Sprint 3 — "External
 * Event Details screen"), confirmed 2026-09-25, since both are the same
 * physical route/component as Sprint 4's create flow:
 * - The List's 6 status tabs are: All/Planning/To Attend/Attended shown
 *   directly, with Not Attending/Elapsed tucked behind a "+2 more" menu
 *   button — not all 6 rendered as top-level tabs.
 * - "AI Relevance" (and "Leads") columns exist but are HIDDEN by
 *   default — must be toggled on via "Configure columns" before they can
 *   be sorted on.
 * - CRITICAL: an event only carries the Planning -> To Attend/Not
 *   Attending -> Attended decision lifecycle (decision buttons, AI
 *   dossier sections) when it originates from the AI-discovery pipeline
 *   ("Generated by AI" tag). An event created manually via "Create
 *   Event" (Sprint 4) is saved DIRECTLY as "Attended" — there is no UI
 *   path to create a fresh Planning-stage event. The AI-seeded Planning
 *   pool in this environment is FIXED and NOT replenishable (6 seed
 *   events total, several already elapsed) — tests that consume one
 *   (TC:2 "To Attend", TC:3 "Attended") permanently remove it from the
 *   pool for future runs. See external-events.page.ts's
 *   findFreshPlanningEvent() for how callers should degrade gracefully
 *   once it's exhausted, rather than fail.
 * - A genuinely PAST-or-present-dated event can still show status
 *   "Planning · Elapsed" (a compound status) once its own schedule has
 *   passed — such an event has NO decision buttons at all (nothing left
 *   to decide), unlike a still-upcoming "Planning" event.
 * - The workspace's action buttons (To Attend/Not Attending, or Mark
 *   Attended once "To Attend") sit ABOVE a tab bar of Planning/Feedback
 *   Form/Leads (N) — "Planning" is a FIXED tab label (holds the AI
 *   dossier + decision card), not a live reflection of current status;
 *   Feedback Form/Leads stay disabled until the event reaches Attended.
 * - The decline ("Not Attending") flow is a real modal — "Reason for Not
 *   Attending" (multi-select) + "Detailed Reason" (textbox), both
 *   required, confirmed via real validation errors ("Select at least
 *   one reason" / "Detailed reason is required"). Its confirm button
 *   reads "Proceed", not "Confirm".
 *
 * Also confirmed (2026-09-25) for Sprint 4's "Create External Event" and
 * "External Events [created by user manually] Details screen" stories:
 * - Every mandatory field (Title/Venue/Date/About/SAITEX Attendees/Score/
 *   Number of Leads/all three Feedback Form free-text fields) shows its
 *   own inline "Required" text on blank submit — SAITEX Attendees shows
 *   "Select at least one attendee" instead.
 * - Cancel navigates straight back to the List screen (`/crm/events`),
 *   discarding whatever was typed — no confirmation prompt.
 * - The SAITEX Attendees popup has NO search/filter input at all — just a
 *   fixed, short `listbox` of 5 employees (Alice Planner, Banupriya
 *   Palanivel, CRM Manager, SamuelRaj Suresh, Sathish Nagarajan), and
 *   typing while it's open does not filter them. TC:5's "type to search"
 *   premise does not hold — it's a plain pick-one-from-a-short-list.
 * - A manually-created event has NO "Planning" tab at all (unlike an
 *   AI-discovered one, which always shows one regardless of status) —
 *   its tab bar is just Overview/Feedback Form/Leads (N). It is born
 *   directly at status "Attended" (tagged "Created manually") because
 *   the create form itself requires the full Feedback Form to be filled
 *   in before it can even submit — there is no reachable "un-attended
 *   manual event" state to test a lock, and no separate empty Feedback
 *   Form to "complete" afterward: the tab immediately renders the
 *   already-submitted answers read-only (no Edit button anywhere on it).
 * - The Leads tab's "Scan & Create"/"Create Customer" affordances are
 *   real `link`s (role `link`, NOT `button` — a common Playwright
 *   locator trap), each a plain `<a href>` to the existing
 *   `/crm/customers/scan`/`/crm/customers/new` routes with `eventId`/
 *   `eventName`/`eventType` query params. Confirmed directly: the
 *   resulting Create Customer form pre-locks CRM Stage to "Lead" and
 *   Origin Type to "External Event" — but ALSO locks the still-required
 *   "Origin" combobox in a permanently disabled state with no visible
 *   way to satisfy it (confirmed after a 3s wait and inspecting its
 *   `disabled` state directly), which blocks Save from ever succeeding
 *   through this entry point. This is a genuine, confirmed app gap, not
 *   a locator guess — see external-events.page.ts's class doc and
 *   test-cases/crm/external-event-manual-details.md's Notes.
 */
export class ExternalEventsLocators {
  readonly createEventButton: Locator;

  // List screen (Sprint 3)
  readonly pageHeading: Locator;
  readonly moreStatusTabsButton: Locator;
  readonly searchInput: Locator;
  readonly configureColumnsButton: Locator;
  readonly columnsDialog: Locator;
  readonly applyColumnsButton: Locator;
  readonly aiRelevanceColumnHeader: Locator;
  readonly emptyStateMessage: Locator;

  // List screen (Sprint 5 — "Build External Events List with Web Crawling")
  readonly filtersButton: Locator;
  readonly filterTypeButton: Locator;
  readonly filterTypeListbox: Locator;
  readonly filterApplyButton: Locator;
  readonly clearAllFiltersButton: Locator;
  readonly noSplitButton: Locator;
  readonly verticalSplitButton: Locator;
  readonly horizontalSplitButton: Locator;
  readonly splitPreviewHeading: Locator;
  readonly paginationSummary: Locator;
  readonly columnHeaders: Locator;
  readonly dataRows: Locator;
  readonly emptyStateHint: Locator;
  readonly resetColumnsButton: Locator;
  readonly closeColumnsDialogButton: Locator;

  // Details/workspace (Sprint 3) — shared with the create flow's own read-back
  readonly toAttendButton: Locator;
  readonly notAttendingButton: Locator;
  readonly markAttendedButton: Locator;
  readonly registerOnlineLink: Locator;
  readonly planningTabButton: Locator;
  readonly feedbackFormTabButton: Locator;
  readonly leadsTabButton: Locator;

  // Details/workspace — manually-created event (Sprint 4)
  readonly overviewTabButton: Locator;
  readonly scanCreateLink: Locator;
  readonly createCustomerLeadLink: Locator;
  readonly leadsEmptyStateMessage: Locator;

  // Decline ("Not Attending") modal
  readonly declineDialog: Locator;
  readonly declineReasonButton: Locator;
  readonly declineDetailedReasonInput: Locator;
  readonly declineProceedButton: Locator;
  readonly declineCancelButton: Locator;

  readonly titleInput: Locator;
  readonly venueInput: Locator;
  readonly dateInput: Locator;
  readonly aboutInput: Locator;

  readonly attendeesButton: Locator;
  readonly scoreRadiogroup: Locator;
  readonly numberOfLeadsInput: Locator;
  readonly wentWellInput: Locator;
  readonly couldBeBetterInput: Locator;
  readonly attendNextEditionsInput: Locator;

  readonly submitButton: Locator;
  readonly cancelButton: Locator;

  readonly confirmDialog: Locator;
  readonly saveEventButton: Locator;
  readonly keepEditingButton: Locator;

  readonly saveFeedbackButton: Locator;
  readonly toast: Locator;

  // Details/workspace — Planning tab (Sprint 5 "External Event Planning"),
  // confirmed against dev 2026-10-15. Header = <h1> title + a sibling
  // status <span> + an "Event: External Event · <type> · <date> · <venue>"
  // line; every Planning section is an <h2> card. No event ID
  // (EV-YYYY-NNN), Owner control, Sales Potential Report or Participation
  // Plan is rendered on dev.
  readonly eventTitleHeading: Locator;
  /** The header row holding the <h1> title and its status <span> — nothing else (confirmed 2026-10-21). */
  readonly eventHeaderTitleRow: Locator;
  readonly eventHeaderStatus: Locator;
  /** The Details screen's own content area (the inner `main`). */
  readonly detailsContent: Locator;
  readonly feedbackFormLockedNote: Locator;
  /** sonner's toast region — always mounted (empty) in the app shell, confirmed 2026-10-21. */
  readonly toastRegion: Locator;
  readonly toasts: Locator;
  readonly eventTypeLine: Locator;
  readonly elapsedBanner: Locator;
  readonly onlineRegistrationNote: Locator;
  readonly notAttendingNote: Locator;
  readonly aiPlaceholderText: Locator;
  readonly ownerControl: Locator;
  readonly backToEventsLink: Locator;
  readonly eventNotFoundMessage: Locator;
  readonly eventLoadErrorMessage: Locator;
  readonly rowsPerPageCombobox: Locator;
  readonly signInButton: Locator;
  readonly ssoPasswordInput: Locator;

  constructor(private readonly page: Page) {
    this.createEventButton = page.getByRole('button', { name: 'Create Event' });

    this.pageHeading = page.getByRole('heading', { name: 'External Events', level: 1 });
    this.moreStatusTabsButton = page.getByRole('button', { name: '+2 more' });
    this.searchInput = page.getByRole('textbox', { name: 'Search' });
    this.configureColumnsButton = page.getByRole('button', { name: 'Configure columns' });
    this.columnsDialog = page.getByRole('dialog', { name: 'Columns' });
    this.applyColumnsButton = this.columnsDialog.getByRole('button', { name: 'Apply' });
    this.aiRelevanceColumnHeader = page.getByRole('button', { name: 'AI Relevance', exact: true });
    this.emptyStateMessage = page.getByText(/no (matching )?(events|records)/i);

    // Sprint 5 additions, confirmed against dev (2026-10-15).
    // The Filters toggle's accessible name gains an "(N applied)" suffix
    // once a filter is applied — e.g. "Filters (1 applied)".
    this.filtersButton = page.getByRole('button', { name: /^Filters( \(\d+ applied\))?$/ });
    // Both the Filters panel's Type dropdown AND the table's Type column
    // sort button are named "Type" — only the dropdown carries
    // aria-expanded, which is what disambiguates them.
    this.filterTypeButton = page
      .getByRole('button', { name: 'Type', exact: true })
      .and(page.locator('[aria-expanded]'));
    this.filterTypeListbox = page.getByRole('listbox', { name: 'Type' });
    this.filterApplyButton = page.getByRole('button', { name: 'Apply', exact: true });
    this.clearAllFiltersButton = page.getByRole('button', { name: 'Clear all', exact: true });
    this.noSplitButton = page.getByRole('button', { name: 'No split' });
    this.verticalSplitButton = page.getByRole('button', { name: 'Vertical split' });
    this.horizontalSplitButton = page.getByRole('button', { name: 'Horizontal split' });
    // The split layouts' preview pane titles the selected event as an h3.
    this.splitPreviewHeading = page.getByRole('heading', { level: 3 });
    this.paginationSummary = page.getByText(/^Showing \d+ to \d+ of \d+/);
    this.columnHeaders = page.getByRole('columnheader');
    this.dataRows = page.getByRole('row').filter({ hasNot: page.getByRole('columnheader') });
    this.emptyStateHint = page.getByText('Try removing a filter or clearing them all.');
    this.resetColumnsButton = this.columnsDialog.getByRole('button', { name: 'Reset to default' });
    this.closeColumnsDialogButton = this.columnsDialog.getByRole('button', {
      name: 'Close',
      exact: true,
    });

    this.toAttendButton = page.getByRole('button', { name: 'To Attend', exact: true });
    this.notAttendingButton = page.getByRole('button', { name: 'Not Attending', exact: true });
    this.markAttendedButton = page.getByRole('button', { name: 'Mark Attended' });
    this.registerOnlineLink = page.getByRole('link', { name: 'Register Online' });
    this.planningTabButton = page.getByRole('button', { name: 'Planning', exact: true });
    this.feedbackFormTabButton = page.getByRole('button', { name: 'Feedback Form', exact: true });
    this.leadsTabButton = page.getByRole('button', { name: /^Leads \(\d+\)$/ });

    this.overviewTabButton = page.getByRole('button', { name: 'Overview', exact: true });
    // Confirmed against the running app: these render as <a href> links,
    // not buttons — role 'link' is required or the locator never matches.
    this.scanCreateLink = page.getByRole('link', { name: 'Scan & Create' });
    this.createCustomerLeadLink = page.getByRole('link', { name: 'Create Customer' });
    this.leadsEmptyStateMessage = page.getByText('No customers created from this event yet.');

    this.declineDialog = page.getByRole('dialog', { name: /^Not Attending/ });
    this.declineReasonButton = this.declineDialog.getByRole('button', {
      name: /Select multiple reasons|reason/i,
    });
    this.declineDetailedReasonInput = this.declineDialog.getByRole('textbox');
    this.declineProceedButton = this.declineDialog.getByRole('button', { name: 'Proceed' });
    this.declineCancelButton = this.declineDialog.getByRole('button', {
      name: 'Cancel',
      exact: true,
    });

    this.titleInput = page.getByRole('textbox', { name: 'External Event Title', exact: false });
    this.venueInput = page.getByRole('textbox', { name: 'External Event Venue', exact: false });
    this.dateInput = page.getByRole('textbox', { name: 'External Event Date', exact: false });
    this.aboutInput = page.getByRole('textbox', { name: 'About the External Event', exact: false });

    // Create Event form: labelled controls. Planning event's Feedback Form
    // (dev, 2026-10-21): the attendees button reads "Who attended?" and the
    // other inputs aren't linked to their labels, so fall back to the first
    // input after the label text.
    // Labels carry a trailing required "*", so match on the start.
    const inputAfter = (label: string): Locator =>
      page
        .getByText(new RegExp(`^${label.replace(/[?]/g, '\\?')}`))
        .first()
        .locator('xpath=following::*[self::input or self::textarea][1]');
    this.attendeesButton = page
      .getByRole('button', { name: 'SAITEX Attendees' })
      .or(page.getByRole('button', { name: 'Who attended?' }));
    this.scoreRadiogroup = page.getByRole('radiogroup', { name: /Score/ });
    this.numberOfLeadsInput = page
      .getByRole('textbox', { name: 'Number of Leads', exact: false })
      .or(page.getByPlaceholder('e.g. 4'));
    this.wentWellInput = page
      .getByRole('textbox', { name: 'What went well?', exact: false })
      .or(inputAfter('What went well?'));
    this.couldBeBetterInput = page
      .getByRole('textbox', { name: 'What could have been better?', exact: false })
      .or(inputAfter('What could have been better?'));
    this.attendNextEditionsInput = page
      .getByRole('textbox', { name: 'Attend next editions?', exact: false })
      .or(inputAfter('Attend next editions?'));

    this.submitButton = page.getByRole('button', { name: 'Submit' });
    this.cancelButton = page.getByRole('button', { name: 'Cancel', exact: true });

    this.confirmDialog = page
      .getByRole('dialog')
      .or(page.getByRole('alertdialog'))
      .filter({ hasText: 'External Event created' });
    this.saveEventButton = this.confirmDialog.getByRole('button', { name: 'Save event' });
    this.keepEditingButton = this.confirmDialog.getByRole('button', { name: 'Keep editing' });

    // Feedback Form Submit opens a "Thanks for the feedback!" dialog; the
    // feedback is only saved from there (dev, 2026-10-21).
    this.saveFeedbackButton = page
      .getByRole('dialog', { name: 'Thanks for the feedback!' })
      .getByRole('button', { name: 'Save feedback' });
    this.toast = page.locator('[data-sonner-toast]').first();

    this.eventTitleHeading = page.getByRole('heading', { level: 1 });
    this.eventHeaderTitleRow = this.eventTitleHeading.locator('xpath=..');
    this.eventHeaderStatus = this.eventTitleHeading.locator('xpath=following-sibling::span[1]');
    this.detailsContent = page.locator('main').last();
    this.feedbackFormLockedNote = page.getByText(/^The Feedback Form opens once/);
    // The shell and the CRM remote each mount one (two on the page).
    this.toastRegion = page.locator('section[aria-label^="Notifications"]').first();
    this.toasts = page.locator('[data-sonner-toast]');
    this.eventTypeLine = page.getByText(/^Event: External Event · /);
    this.elapsedBanner = page.getByText(
      'The schedule of this External Event has elapsed — it is marked as Elapsed.',
    );
    this.onlineRegistrationNote = page.getByText(/^Online registration exists — /);
    this.notAttendingNote = page.getByText(/^Not Attending — /);
    this.aiPlaceholderText = page.getByText(
      /^Unfortunately, no relevant information is available for the .+ online\.$/,
    );
    this.ownerControl = page
      .getByRole('combobox', { name: /owner/i })
      .or(page.getByRole('button', { name: /^owner/i }))
      .or(page.getByLabel(/^owner$/i));
    this.backToEventsLink = page.getByRole('link', { name: 'Back to external events' });
    this.eventNotFoundMessage = page.getByText('Event not found.', { exact: true });
    this.eventLoadErrorMessage = page.getByText(/^Couldn't load this event\./);
    this.rowsPerPageCombobox = page.getByRole('combobox', { name: 'Rows per page' });
    this.signInButton = page.getByRole('button', { name: 'Sign in' });
    this.ssoPasswordInput = page.locator('input[type="password"]');
  }

  scoreRadio(value: number): Locator {
    return this.scoreRadiogroup.getByRole('radio', { name: String(value), exact: true });
  }

  attendeeOption(name: string): Locator {
    return this.page.getByRole('option', { name, exact: true });
  }

  /** A status tab button on the List screen, by its bare name (e.g. "Planning") — accessible name carries a live count suffix, e.g. "Planning 5". */
  statusTab(name: string): Locator {
    return this.page.getByRole('button', { name: new RegExp(`^${name} \\d+$`) });
  }

  /** A row in the events table, by its Event title. */
  eventRow(title: string): Locator {
    return this.page.getByRole('row').filter({ hasText: title });
  }

  /** A toggle checkbox in the Configure Columns dialog. */
  columnToggle(columnName: string): Locator {
    return this.columnsDialog.getByRole('checkbox', { name: `Toggle ${columnName}` });
  }

  /** A reason chip option in the decline modal's multi-select (e.g. "Travel constraints"). */
  declineReasonOption(name: string): Locator {
    return this.page.getByRole('option', { name, exact: true });
  }

  /** Every one of this form's inline "Required" errors — one per blank mandatory field. */
  requiredFieldErrors(): Locator {
    return this.page.getByText('Required', { exact: true });
  }

  /** An option in the Filters panel's Type dropdown (e.g. "Trade Fair"). */
  filterTypeOption(type: string): Locator {
    return this.filterTypeListbox.getByRole('option', { name: type, exact: true });
  }

  /** The removable chip shown under the toolbar for an applied filter, e.g. "Type: Trade Fair". */
  removeFilterChip(label: string): Locator {
    return this.page.getByRole('button', { name: `Remove ${label}`, exact: true });
  }

  /** A column's header cell, by its visible label (accessible name also carries "Resize <label> column"). */
  columnHeader(label: string): Locator {
    return this.page.getByRole('columnheader', {
      name: new RegExp(`^${escapeRegExp(label)} Resize`),
    });
  }

  /** The clickable sort button inside a column header. */
  columnSortButton(label: string): Locator {
    return this.columnHeader(label).getByRole('button', { name: label, exact: true });
  }

  /** The sort indicator icon inside a column header's sort button. */
  columnSortIcon(label: string): Locator {
    return this.columnSortButton(label).locator('svg');
  }

  /** The drag handle for a column in the Configure Columns dialog. */
  columnDragHandle(columnName: string): Locator {
    return this.columnsDialog.getByRole('button', { name: `Drag ${columnName}`, exact: true });
  }

  /** A row checkbox in the table layouts (No split / Horizontal split), by its row's Event title. */
  rowCheckbox(title: string): Locator {
    return this.eventRow(title).getByRole('checkbox');
  }

  /** A list item in the Vertical split's left-hand list — a button named "Select row <title> …" or "Deselect row <title> …" once checked. */
  splitListItem(title: string): Locator {
    return this.page.getByRole('button', {
      name: new RegExp(`^(Select|Deselect) row ${escapeRegExp(title)}`),
    });
  }

  /** A Details-screen section card (e.g. "Participant Summary", "System"), by its <h2> — the card is the heading's 3rd ancestor (confirmed against dev). */
  sectionCard(name: string): Locator {
    return this.page
      .getByRole('heading', { level: 2, name, exact: true })
      .locator('xpath=../../..');
  }

  sectionHeading(name: string | RegExp): Locator {
    return this.page.getByRole('heading', { level: 2, name });
  }

  /** Body rows of the List table (header row excluded). */
  tableRows(): Locator {
    return this.page.getByRole('row').filter({ hasNot: this.page.getByRole('columnheader') });
  }

  /** List rows whose Type cell is exactly `type` (e.g. "Trade Fair", "Other"). */
  rowsOfType(type: string): Locator {
    return this.tableRows().filter({
      has: this.page.getByRole('cell', { name: type, exact: true }),
    });
  }

  /** List rows from the AI-discovery pipeline — everything that isn't a manual "Other" event. */
  aiEventRows(): Locator {
    return this.tableRows().filter({
      hasNot: this.page.getByRole('cell', { name: 'Other', exact: true }),
    });
  }
}
