/**
 * Test data for 20-routing-templates.spec.ts. Every template it creates is
 * its own, named with RT_TAG (so it can be found and deleted from the
 * backend). Codes are generated by dev (RT-0001…) on the first Save draft.
 *
 * Two rules of the screen shape this file:
 * - One live template per cycle kind × product type × wash type: publishing
 *   a template retires the Active one on the same triple. Templates are only
 *   published on a triple no live template uses (freeTriple), and publish()
 *   refuses to confirm a Publish dialog that says it would retire anything.
 * - Templates can't be deleted. Cleanup retires this file's Active ones;
 *   Drafts stay (harmless, never derived from) and carry the tag.
 */
export const PREFIX = 'QA-RT';

export function rtName(tag: string): string {
  return `QA-AUTO ${tag} — routing-templates test data (pw-hybrid-framework). Safe to delete.`;
}

export const NO_CATALOGUE =
  'Environment gap: the cases need steps from three departments and product and wash types to ' +
  'publish on, but the routing-template activity picker offers only SEWING activities (all QA-AUTO or ' +
  'test data) and the lookups hold no product or wash types (uat on 2026-11-25)';

/** A cycle kind × product type × wash type, by the labels the editor shows. */
export interface Triple {
  cycleKind: string;
  productType?: string;
  washType?: string;
}

/** Activities a worker builds steps from: three from different departments. */
export interface Catalogue {
  codes: [string, string, string];
  options: ActivityOption[];
}

/**
 * Reads the activity picker on a never-saved draft. Returns null when it
 * lists nothing (NO_CATALOGUE). Picks one activity from each of the first
 * three departments, skipping other suites' QA-AUTO activities (they can be
 * retired by those suites mid-run).
 */
export async function readCatalogue(page: Page): Promise<Catalogue | null> {
  const editor = new RoutingTemplateEditorPage(page);
  await editor.openNew();
  await editor.addStepAndOpenPicker();
  if (!(await editor.pickerHasActivities())) return null;
  const options = await editor.pickerCatalogue();
  await editor.closeActivityPicker();
  const usable = options.filter(
    (o) => !/QA-AUTO|TEST|WIZARD/i.test(`${o.code} ${o.name} ${o.group}`),
  );
  const byGroup = new Map<string, string>();
  for (const o of usable) if (!byGroup.has(o.group)) byGroup.set(o.group, o.code);
  const codes = [...byGroup.values()];
  if (codes.length < 3) return null;
  return { codes: [codes[0]!, codes[1]!, codes[2]!], options };
}

/** Triples this worker has handed out (module state is per worker). */
const usedTriples = new Set<string>();

/** A stable hash, so every worker computes the same share of triples for itself. */
function shareOf(key: string, workers: number): number {
  let h = 0;
  for (const ch of key) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return h % workers;
}

/**
 * A random cycle kind × product type × wash type that no live template uses
 * (both types set, so it never collides with a seeded any-product template).
 * "Live" is read fresh from the list on every call — Active templates and
 * first submissions awaiting approval, whoever made them (an approval turns
 * the latter Active). Each parallel worker draws only from its own stable
 * share of the triples (a hash of the triple, modulo the worker count), so two
 * of this suite's workers never pick the same one, and a worker never reuses a
 * triple. Another run, or a person, can still publish between this read and
 * the send; sendForApproval() refuses a send that would replace a live template.
 */
export async function freeTriple(page: Page): Promise<Triple> {
  const { templates, lookups } = await snapshot(page);
  const live = new Set(
    templates
      .filter((t) => t.statusCode === 'active' || t.statusCode === 'pending_approval')
      .map((t) => `${t.cycleKindId}|${t.productType ?? ''}|${t.washType ?? ''}`),
  );
  const kinds = lookups.cycleKinds.filter((k) => k.active);
  const products = lookups.productTypes.filter((p) => p.active !== false);
  const washes = lookups.washTypes.filter((w) => w.active !== false);
  const workers = Math.max(1, test.info().config.workers);
  const me = Number(process.env.TEST_PARALLEL_INDEX ?? 0) % workers;
  const mine: Triple[] = [];
  for (const k of kinds)
    for (const p of products)
      for (const w of washes) {
        const key = `${k.id}|${p.code}|${w.code}`;
        const used = usedTriples.has(`${k.label}|${p.label}|${w.label}`);
        if (!live.has(key) && !used && shareOf(key, workers) === me)
          mine.push({ cycleKind: k.label, productType: p.label, washType: w.label });
      }
  if (!mine.length)
    throw new Error(
      `No cycle kind × product type × wash type is free to publish on in worker ${me} of ${workers}'s share`,
    );
  const pick = mine[Math.floor(Math.random() * mine.length)]!;
  usedTriples.add(`${pick.cycleKind}|${pick.productType}|${pick.washType}`);
  return pick;
}

/** A cycle kind for drafts that are never published (no triple to protect). */
export function anyCycleKind(snapshot: RoutingTemplatesSnapshot): Triple {
  const kind = snapshot.lookups.cycleKinds.find((k) => k.active);
  if (!kind) throw new Error('No active cycle kind');
  return { cycleKind: kind.label };
}

export interface BuiltTemplate {
  code: string;
  tag: string;
  name: string;
  triple: Triple;
}

export interface TemplateOptions {
  triple: Triple;
  /** Activities for the steps, in order. */
  steps: string[];
  /** Links as [from, to] pairs (to waits on from, after finish). Default: a chain. */
  links?: [number, number][];
  description?: string;
}

/**
 * Builds a template on a never-saved draft (header, steps, links) without
 * saving it; returns its tag and name. The page is left on the editor.
 */
export async function buildDraft(
  page: Page,
  options: TemplateOptions,
): Promise<{ tag: string; name: string }> {
  const tag = uniqueTag(PREFIX);
  const name = rtName(tag);
  const editor = new RoutingTemplateEditorPage(page);
  await editor.openNew();
  await editor.fillHeader({ ...options.triple, name, description: options.description });
  for (const code of options.steps) await editor.addStepWith(code);
  const links =
    options.links ?? options.steps.slice(1).map((_, i) => [i + 1, i + 2] as [number, number]);
  for (const [from, to] of links) await editor.addLink(to, { from });
  return { tag, name };
}

/** Builds and saves a Draft; returns it. The page is left on its editor. */
export async function createTemplate(page: Page, options: TemplateOptions): Promise<BuiltTemplate> {
  const { tag, name } = await buildDraft(page, options);
  const editor = new RoutingTemplateEditorPage(page);
  const saved = await editor.saveDraft();
  expect(saved.outcome, `save routing template ${tag}`).toBe('saved');
  if (saved.outcome !== 'saved') throw new Error('unreachable');
  trackCode(PREFIX, saved.code);
  return { code: saved.code, tag, name, triple: options.triple };
}

/** The person the suite's approval policies route to (the logged-in Planning user, an Approvals admin). */
export const ALICE = 'Alice Planner';

/**
 * Makes `make()`'s result once per test run (per `key`) and hands the same
 * value to every later caller in that run — a failed case restarts its
 * worker, which runs beforeAll again, and approval policies can't be deleted,
 * so each restart must not create another one. Keyed by the Playwright
 * runner's pid, in the OS temp dir; a file older than 6 h is ignored.
 */
export async function oncePerRun<T>(key: string, make: () => Promise<T>): Promise<T> {
  // Files of earlier runs (over 6 h old) are removed, so the temp folder doesn't collect them.
  for (const f of fs.readdirSync(os.tmpdir()))
    if (f.startsWith('pw-routing-templates-')) {
      const old = path.join(os.tmpdir(), f);
      if (Date.now() - fs.statSync(old).mtimeMs >= 6 * 60 * 60 * 1000)
        fs.rmSync(old, { force: true });
    }
  const file = path.join(os.tmpdir(), `pw-routing-templates-${process.ppid}-${key}.json`);
  if (fs.existsSync(file) && Date.now() - fs.statSync(file).mtimeMs < 6 * 60 * 60 * 1000)
    return JSON.parse(fs.readFileSync(file, 'utf8')) as T;
  const value = await make();
  fs.writeFileSync(file, JSON.stringify(value));
  return value;
}

// Per worker (module state is per worker): the suite's own approval policies.
const policies: string[] = [];

/** A run-unique policy name carrying the QA-AUTO marker. */
export function policyName(label: string): string {
  return rtName(`${uniqueTag('RT-P')} ${label}`);
}

/**
 * Creates an INACTIVE one-level "Routing template" approval policy (Alice
 * approves) and records it for the afterAll check. An active policy decides
 * how every routing template is sent for approval, for everyone, so the
 * suite switches its policy on only for the seconds a send needs and off
 * again in the same call (sendForApproval). Policies can't be deleted.
 */
export async function createPolicy(page: Page, name: string): Promise<string> {
  const list = new ApprovalPoliciesPage(page);
  const form = new ApprovalPolicyFormPage(page);
  await list.open();
  await list.expectLoaded();
  await list.openNew();
  await form.expectOnNew();
  await form.fillNew({
    name,
    description: rtName('policy'),
    entityType: 'Routing template',
    active: false,
    levels: [{ name: 'QA review', from: 'Users', who: [ALICE] }],
  });
  policies.push(name);
  const outcome = await form.saveOk();
  expect(outcome.status, `create policy ${name}`).toBe(201);
  return name;
}

/** Puts a policy made earlier in the run (oncePerRun) on this worker's afterAll check. */
export function watchPolicy(name: string): void {
  if (!policies.includes(name)) policies.push(name);
}

async function setPolicyActive(page: Page, name: string, active: boolean): Promise<void> {
  const list = new ApprovalPoliciesPage(page);
  const form = new ApprovalPolicyFormPage(page);
  await list.openPolicy(name);
  await form.applyChanges({ active });
  await form.saveIfChanged();
}

/** What a policy's name carries when this suite made it (rtName's tail). */
const POLICY_MARKER = 'routing-templates test data';

/**
 * Switches the policy off and checks that it stuck (the list reads Inactive).
 * Retried — a policy left active routes other people's sends to the QA chain —
 * and THROWS when the third attempt still leaves it active.
 */
async function deactivate(page: Page, name: string): Promise<void> {
  const list = new ApprovalPoliciesPage(page);
  let last = '';
  for (let attempt = 1; attempt <= 3; attempt += 1) {
    try {
      await setPolicyActive(page, name, false);
      await list.findRow(name);
      await list.expectCell(name, 'Status', 'Inactive');
      return;
    } catch (error) {
      last = String(error).split('\n')[0]!;
    }
  }
  throw new Error(
    `QA-AUTO policy "${name}" is STILL ACTIVE after 3 attempts to switch it off: ${last}`,
  );
}

/**
 * Start-of-run sweep: a killed run (Ctrl-C, CI cancel, a sleeping Mac) can
 * leave this suite's policy Active, which keeps routing other people's
 * routing-template sends to the QA chain. Switches off every Active policy
 * that carries this suite's marker; throws if one stays on. Run once per run.
 */
export async function sweepActivePolicies(page: Page): Promise<string[]> {
  const list = new ApprovalPoliciesPage(page);
  await list.open();
  await list.expectLoaded();
  await list.selectTab('Active');
  await list.search(POLICY_MARKER);
  await list.settle();
  let names: string[] = [];
  await expect
    .poll(
      async () => {
        if (await list.gridIsEmpty()) {
          names = [];
          return true;
        }
        // Rows scrolled out of the grid's viewport render empty: skip those.
        const shown = (await list.columnValues('Policy')).filter(Boolean);
        names = shown.filter((n) => n.includes(POLICY_MARKER));
        return shown.every((n) => n.includes(POLICY_MARKER));
      },
      { message: `Active policies should all match "${POLICY_MARKER}"`, timeout: WAIT.NAVIGATION },
    )
    .toBe(true);
  for (const name of names) {
    await deactivate(page, name);
    console.log(
      `QA-AUTO sweep (routing-templates): left-over active policy "${name}" switched off`,
    );
  }
  return names;
}

/**
 * Sends the open template (Draft, or Active with a pending revision) for
 * approval: switches `policy` on, clicks "Send for approval", switches it
 * off again — even when the send fails. Refuses (and throws) if the app
 * says the approval would replace another template ("Send for approval?"
 * dialog) — the suite never takes over someone else's live template.
 * Leaves the page on the template. Returns the request code.
 */
export async function sendForApproval(page: Page, policy: string): Promise<string> {
  const here = new URL(page.url()).pathname;
  const panel = new ApprovalPanelPage(page);
  const { anyPendingBanner: pending, replaceDialog: replaces } = panel.locators;
  // The policy is switched off again whether the send worked or not; a failure
  // of that clean-up must not hide the send's own error.
  const switchOff = async () => {
    await deactivate(page, policy);
    await page.goto(here);
  };
  let code: string;
  try {
    await setPolicyActive(page, policy, true);
    await page.goto(here);
    await expect(panel.locators.sendForApprovalButton).toBeEnabled({ timeout: WAIT.PAGE_LOAD });
    await panel.locators.sendForApprovalButton.click();
    await expect(pending.or(replaces).first()).toBeVisible({
      timeout: WAIT.NAVIGATION,
    });
    if (await replaces.isVisible()) {
      const text = await replaces.innerText();
      await replaces.getByRole('button', { name: 'Cancel' }).click();
      throw new Error(`Approving would replace another template — not sent: ${text}`);
    }
    code = await panel.requestCode();
  } catch (error) {
    try {
      await switchOff();
    } catch (cleanup) {
      throw new Error(
        `${String(error).split('\n')[0]} — AND the clean-up failed: ${String(cleanup).split('\n')[0]}`,
      );
    }
    throw error;
  }
  await switchOff();
  return code;
}

/**
 * Approves the template's pending request (the logged-in user is an Approvals
 * admin). Refuses — cancels the dialog and throws — when the Approve dialog
 * says approving would replace or retire a template: the suite never retires
 * someone else's live template.
 */
export async function approvePending(page: Page): Promise<void> {
  const panel = new ApprovalPanelPage(page);
  const { approveButton, dialog, dialogConfirm } = panel.locators;
  await approveButton.click();
  await expect(dialog).toBeVisible();
  const text = await dialog.innerText();
  if (/replac|retir/i.test(text)) {
    await dialog.getByRole('button', { name: 'Cancel' }).click();
    throw new Error(`Approving would replace or retire a template — not approved: ${text}`);
  }
  await dialog.getByRole('textbox').first().fill('QA-AUTO routing-templates suite');
  await dialogConfirm.click();
  await expect(dialog).toBeHidden({ timeout: WAIT.SERVER });
  await expect(panel.locators.anyPendingBanner).toHaveCount(0, { timeout: WAIT.SERVER });
}

/**
 * Validates and activates the open (saved) template: sends it for approval
 * under `policy` and approves it (revision 1, Active).
 */
export async function publish(page: Page, policy: string): Promise<void> {
  const editor = new RoutingTemplateEditorPage(page);
  expect(await editor.validate(), 'Validate before sending for approval').toEqual([]);
  await sendForApproval(page, policy);
  await approvePending(page);
  await editor.expectStatus(/^Active · rev \d+$/);
}

/** Creates a template, publishes it (revision 1, Active) and returns it. */
export async function createActive(
  page: Page,
  policy: string,
  options: TemplateOptions,
): Promise<BuiltTemplate> {
  const built = await createTemplate(page, options);
  await publish(page, policy);
  return built;
}

/** Opens a template's editor from the list. */
export async function openTemplate(page: Page, code: string): Promise<void> {
  const list = new RoutingTemplatesListPage(page);
  await list.findRow(code);
  await list.openRow(code);
  const editor = new RoutingTemplateEditorPage(page);
  await editor.expectLoaded(code);
  await editor.startEditingDraft();
}

/** Reads what the list loads (templates + lookups), for picking triples. */
export async function snapshot(page: Page): Promise<RoutingTemplatesSnapshot> {
  return new RoutingTemplatesListPage(page).openReadingTemplates();
}

/** Retires a QA-AUTO Active template (cancelling a pending revision first). */
async function retireTemplate(page: Page, code: string): Promise<void> {
  await openTemplate(page, code);
  const editor = new RoutingTemplateEditorPage(page);
  const panel = new ApprovalPanelPage(page);
  // A request still pending (a case failed midway): an Approvals admin may withdraw it.
  if (await editor.locators.withdrawButton.isVisible()) {
    await panel.withdraw('QA-AUTO routing-templates suite cleanup');
    await expect(editor.locators.withdrawButton).toBeHidden({ timeout: WAIT.SERVER });
  }
  // A Draft (even one returned from approval) can't be retired or deleted: it stays, tagged.
  if (/Draft/.test(await editor.headerText())) return;
  if (await editor.locators.cancelRevisionButton.isVisible()) {
    await editor.openCancelRevision();
    await editor.confirmCancelRevision();
  }
  const list = new RoutingTemplatesListPage(page);
  await list.findRow(code);
  await list.openRetire(code);
  await list.expectRetireDialog(code);
  await list.expectSuccessor('No successor — no longer made');
  await list.confirmRetire();
}

/**
 * The afterAll for 20-routing-templates.spec.ts: withdraws requests still
 * pending, retires this file's Active templates and checks none of this
 * worker's approval policies is left active.
 */
export function cleanUpRoutingTemplates(): void {
  test.afterAll(async ({ browser }) => {
    test.setTimeout(300_000);
    const page = await setupPage(browser);
    page.setDefaultTimeout(30_000);
    const stuck: string[] = [];
    try {
      const list = new ApprovalPoliciesPage(page);
      for (const name of policies.splice(0)) {
        try {
          await list.findRow(name);
          if ((await list.cellValue(name, 'Status')) !== 'Inactive') {
            await deactivate(page, name);
            console.log(`QA-AUTO cleanup (routing-templates): policy "${name}" deactivated`);
          }
        } catch (error) {
          stuck.push(`"${name}": ${String(error).split('\n')[0]}`);
        }
      }
    } finally {
      await page.close();
    }
    // A policy left on keeps routing other people's sends to the QA chain: a failure, never a warning.
    if (stuck.length)
      throw new Error(`QA-AUTO approval policy left Active or unverifiable: ${stuck.join('; ')}`);
  });
  cleanUpAfterAll([
    {
      prefix: PREFIX,
      lists: (page: Page) => [new RoutingTemplatesListPage(page)],
      // Drafts can't be deleted or retired; Retired ones are done.
      done: (row: string) => /\b(Retired|Draft)\b/.test(row) && !/pending/i.test(row),
      clean: (page: Page, code: string) => retireTemplate(page, code),
    },
  ]);
}

